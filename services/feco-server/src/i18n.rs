//! Ngôn ngữ giao diện (spec platform-support, "Ngôn ngữ"): tiếng Việt, tiếng Anh, tiếng Nhật
//! (thay đổi web-ui-and-japanese) và tiếng Pháp (launcher-windows-and-web-profile, QUESTIONS 79),
//! mặc định theo trình duyệt, đổi được bằng liên kết `/lang/{vi|en|ja|fr}` (lưu cookie). Bản tiếng
//! Nhật nằm ở `i18n_ja.rs`, tiếng Pháp ở `i18n_fr.rs`; nội dung do hệ thống tạo chưa có bản dịch
//! thì hiện tiếng Anh.

use axum::{
    extract::FromRequestParts,
    http::{header, request::Parts},
};

pub const COOKIE: &str = "feco_lang";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    Vi,
    En,
    Ja,
    Fr,
}

impl Lang {
    pub fn parse(s: &str) -> Option<Lang> {
        match s {
            "vi" => Some(Lang::Vi),
            "en" => Some(Lang::En),
            "ja" => Some(Lang::Ja),
            "fr" => Some(Lang::Fr),
            _ => None,
        }
    }

    pub const fn code(self) -> &'static str {
        match self {
            Lang::Vi => "vi",
            Lang::En => "en",
            Lang::Ja => "ja",
            Lang::Fr => "fr",
        }
    }

    pub const ALL: [Lang; 4] = [Lang::Vi, Lang::En, Lang::Fr, Lang::Ja];

    /// Tên ngôn ngữ viết bằng chính ngôn ngữ đó (nút chọn ngôn ngữ).
    pub const fn native_name(self) -> &'static str {
        match self {
            Lang::Vi => "Tiếng Việt",
            Lang::En => "English",
            Lang::Ja => "日本語",
            Lang::Fr => "Français",
        }
    }

    /// Nội dung chỉ có tiếng Việt và tiếng Anh: chọn tiếng Việt hay không (tiếng Nhật dùng tiếng Anh).
    pub const fn is_vi(self) -> bool {
        matches!(self, Lang::Vi)
    }

    /// Chọn ngôn ngữ: cookie `feco_lang` trước, rồi `Accept-Language`, mặc định tiếng Việt.
    pub fn detect(cookie: Option<&str>, accept_language: Option<&str>) -> Lang {
        if let Some(lang) = cookie.and_then(|c| {
            c.split(';')
                .filter_map(|p| p.trim().split_once('='))
                .find(|(k, _)| *k == COOKIE)
                .and_then(|(_, v)| Lang::parse(v))
        }) {
            return lang;
        }
        // Chỉ xét ngôn ngữ được ưu tiên đầu tiên.
        match accept_language
            .and_then(|a| a.split(',').next())
            .map(|first| first.trim().to_ascii_lowercase())
        {
            Some(l) if l.starts_with("en") => Lang::En,
            Some(l) if l.starts_with("ja") => Lang::Ja,
            Some(l) if l.starts_with("fr") => Lang::Fr,
            _ => Lang::Vi,
        }
    }

    pub fn t(self, key: &str) -> &'static str {
        t(self, key)
    }
}

impl<S: Send + Sync> FromRequestParts<S> for Lang {
    type Rejection = std::convert::Infallible;

    async fn from_request_parts(parts: &mut Parts, _: &S) -> Result<Self, Self::Rejection> {
        let get = |h| parts.headers.get(h).and_then(|v| v.to_str().ok());
        Ok(Lang::detect(
            get(header::COOKIE),
            get(header::ACCEPT_LANGUAGE),
        ))
    }
}

